# assignment operators

n1 = 10

n2 = 20

print(f"n1 = {n1}, n2 = {n2}")

# n1 = n1 + n2
n1 += n2
print(f"n1 = {n1}")

# n1 = n1 - n2
n1 -= n2
print(f"n1 = {n1}")

# n1 = n1 * n2
n1 *= n2
print(f"n1 * n2 = {n1}")

# n1 = n1 / n2
n1 /= n2
print(f"n1 / n2 ={n1}")

# n1 = n1 // n2
# n1 //= n2

# n1 = n1 % n2
# n1 %=n2

# n1 = n1 ** n2
n1 **=2
print(f"n1**=n2 = {n1}")

